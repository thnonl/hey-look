import fs from 'node:fs';
import { sleep, startHarness, languageJs } from './cdp-harness.mjs';
const H = await startHarness('shot', { vitePort0: 6030 });
const { evaluate, cdp } = H;
await H.openApp('lang=en&os=macos&macnotify-denied', 960, 560);
await evaluate(`window.__store.getState().setDialog({ type: 'settings', tab: 'tray' }); window.__store.getState().setPrefs({ theme: 'dark' }); 1`);
await sleep(600);
await evaluate(languageJs('de')); await sleep(300);
const r = await cdp('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('D:/tmp/wp5-macchk/shot-macnotify-de-dark.png', Buffer.from(r.data, 'base64'));
await H.shutdown();
