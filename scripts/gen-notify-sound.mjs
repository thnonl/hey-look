#!/usr/bin/env node
// The new-mail sound of Hey Look! (1.0.7 W13.8, REQ-13.8.7): "10-pop", a soft bubble pop of 0.35 s, synthesised here, no samples and no third-party audio (MIT like the rest of the repository).
// WAV, 44.1 kHz, 16-bit PCM, mono, 3 ms fade-in, exponential fade-out, RMS -19 dBFS, peak at most -3 dBFS. Deterministic: the same bytes on every run and machine.
// The recipe is the "10-pop" of the sample set the owner chose from (make-sounds.mjs); only that sound is kept.
//   node scripts/gen-notify-sound.mjs            writes src-tauri/sounds/new-mail.wav
//   node scripts/gen-notify-sound.mjs --check    compares the committed file with the generated bytes (exit 1 when they differ)
//   import { generate } from "./gen-notify-sound.mjs"   -> a Buffer
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SR = 44100;
const TAU = Math.PI * 2;
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = path.join(ROOT, "src-tauri", "sounds", "new-mail.wav");
/** SHA-256 of the sound the owner approved (spec-107-wp13 W13.8); the generator must reproduce it byte for byte. */
export const APPROVED_SHA256 = "13d5defb4accc177aefca80270bbb0fb68b318b657f4e216ec07d6148e6de4ad";

const buf = (sec) => new Float64Array(Math.round(sec * SR));

// a decaying partial: frequency `f` (or the glide `glide(t)`), amplitude, decay `tau` (s), start (s), attack (s)
function partial(b, f, amp, tau, start = 0, attack = 0.004, glide = null) {
  const s0 = Math.round(start * SR);
  let ph = 0;
  for (let i = s0; i < b.length; i++) {
    const t = (i - s0) / SR;
    const env = Math.min(1, t / attack) * Math.exp(-t / tau);
    if (env < 1e-5 && t > attack) break;
    const fr = glide ? glide(t) : f;
    ph += (TAU * fr) / SR;
    b[i] += amp * env * Math.sin(ph);
  }
}

// fades, optional soft saturation (`drive`), then the peak is set to -3 dBFS
function finish(b, drive = 1) {
  const n = b.length;
  const fi = Math.round(0.003 * SR);
  for (let i = 0; i < fi; i++) b[i] *= 0.5 - 0.5 * Math.cos((Math.PI * i) / fi);
  const fo = Math.round(0.06 * SR);
  for (let i = 0; i < fo; i++) {
    const u = i / fo;
    b[n - fo + i] *= Math.exp(-7 * u) * (1 - u);
  }
  b[n - 1] = 0;
  const out = new Float64Array(n);
  for (let i = 0; i < n; i++) out[i] = drive > 1 ? Math.tanh(drive * b[i]) : b[i];
  let pk = 0;
  for (const v of out) pk = Math.max(pk, Math.abs(v));
  const g = Math.pow(10, -3 / 20) / pk;
  for (let i = 0; i < n; i++) out[i] *= g;
  return out;
}
const rmsDb = (b) => {
  let s = 0;
  for (const v of b) s += v * v;
  return 10 * Math.log10(s / b.length);
};

// raise the RMS of a peaky sound toward the common target (the drive is capped)
function finishLoud(b, target = -19, maxDrive = 3) {
  let d = 1;
  let o = finish(Float64Array.from(b), 1);
  while (rmsDb(o) < target && d < maxDrive) {
    d += 0.2;
    o = finish(Float64Array.from(b), d);
  }
  return o;
}

/** The samples of the pop (Float64Array, -1 to 1). */
export function pop() {
  const b = buf(0.35);
  partial(b, 0, 1, 0.025, 0, 0.002, (t) => 220 + 480 * (1 - Math.exp(-t / 0.02)));
  partial(b, 0, 0.2, 0.015, 0, 0.002, (t) => 440 + 960 * (1 - Math.exp(-t / 0.02)));
  const data = finishLoud(b);
  // the level of the whole sample set is brought down to -19 dBFS (the set's quietest member decides; for the pop it is -19)
  const r = rmsDb(data);
  const T = -19;
  if (r > T) {
    const g = Math.pow(10, (T - r) / 20);
    for (let k = 0; k < data.length; k++) data[k] *= g;
  }
  return data;
}

/** The WAV file: 44-byte header and 16-bit little-endian samples. */
export function wav(data) {
  const n = data.length;
  const out = Buffer.alloc(44 + n * 2);
  out.write("RIFF", 0);
  out.writeUInt32LE(36 + n * 2, 4);
  out.write("WAVE", 8);
  out.write("fmt ", 12);
  out.writeUInt32LE(16, 16);
  out.writeUInt16LE(1, 20);
  out.writeUInt16LE(1, 22);
  out.writeUInt32LE(SR, 24);
  out.writeUInt32LE(SR * 2, 28);
  out.writeUInt16LE(2, 32);
  out.writeUInt16LE(16, 34);
  out.write("data", 36);
  out.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) out.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(data[i] * 32767))), 44 + i * 2);
  return out;
}

export const generate = () => wav(pop());

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bytes = generate();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT) : null;
    if (!have || !have.equals(bytes)) {
      console.error(`gen-notify-sound: ${path.relative(ROOT, OUT)} differs from the generated sound`);
      process.exit(1);
    }
    console.log("gen-notify-sound: ok (the committed file is the generated one)");
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, bytes);
    console.log(`gen-notify-sound: wrote ${path.relative(ROOT, OUT)} (${bytes.length} bytes)`);
  }
}
