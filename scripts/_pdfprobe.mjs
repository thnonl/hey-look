import fs from 'node:fs';
import { sleep, startHarness } from './cdp-harness.mjs';
const H = await startHarness('pdfprobe', { vitePort0: 6040 });
const { evaluate, cdp } = H;
const name = process.argv[2] || 'one-page.pdf';
const b64 = fs.readFileSync(name.includes(':') ? name : new URL(`./fixtures/pdf/${name}`, import.meta.url)).toString('base64');
const logs = [];
H.on((m) => { if (m.method === 'Runtime.consoleAPICalled') logs.push(m.params.type + ': ' + m.params.args.map((a) => a.value ?? a.description).join(' ')); if (m.method === 'Runtime.exceptionThrown') logs.push('EXC ' + JSON.stringify(m.params.exceptionDetails).slice(0, 300)); if (m.method === 'Log.entryAdded') logs.push('LOG ' + m.params.entry.text); });
await cdp('Log.enable');
await H.openApp('lang=en&os=macos', 1280, 800);
await evaluate(`window.__mockPdf = { 'agenda.pdf': ${JSON.stringify(b64)} }; window.__store.getState().select('tlayer'); 1`);
await sleep(800);
await evaluate(`(() => { const b = document.querySelector('.rp-head .icon-btn[aria-label="Expand all"]'); if (b) b.click(); })()`);
await sleep(800);
await evaluate(`(() => { const c = [...document.querySelectorAll('.att-card')].find((x) => x.textContent.includes('agenda.pdf')); c.dispatchEvent(new MouseEvent('dblclick', { bubbles: true })); })()`);
await sleep(4000);
const info = await evaluate(`(() => { const s = document.querySelector('.pv-pdfjs'); return JSON.stringify({ state: s?.dataset.state, worker: s?.dataset.worker, page: s?.dataset.page, pages: document.querySelectorAll('.pv-page').length, canvases: document.querySelectorAll('.pv-page canvas').length, text: document.querySelectorAll('.pv-text-layer span').length, head: document.querySelector('.pv-head')?.innerText }); })()`);
console.log(info);
const r = await cdp('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('D:/tmp/wp5-macchk/probe.png', Buffer.from(r.data, 'base64'));
console.log(logs.slice(0, 20).join('\n'));
await H.shutdown();
